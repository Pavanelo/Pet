CREATE DATABASE IF NOT EXISTS petpet CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE petpet;

CREATE TABLE IF NOT EXISTS usuarios (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(180) NOT NULL UNIQUE,
    contato VARCHAR(30) NOT NULL,
    cargo VARCHAR(60) NOT NULL DEFAULT 'Tutor',
    senha_hash VARCHAR(128) NOT NULL,
    senha_salt VARCHAR(32) NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS pets (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    usuario_id INT UNSIGNED NOT NULL,
    nome VARCHAR(120) NOT NULL,
    especie VARCHAR(40) NOT NULL,
    raca VARCHAR(100) NULL,
    sexo VARCHAR(20) NULL,
    data_nascimento DATE NULL,
    peso DECIMAL(6,2) NULL,
    cor VARCHAR(80) NULL,
    castrado TINYINT(1) NOT NULL DEFAULT 0,
    microchip VARCHAR(80) NULL,
    observacoes TEXT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_pets_usuario (usuario_id),
    CONSTRAINT fk_pets_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
);
